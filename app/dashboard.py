def render_detection_records(data: dict) -> None:
    """Display model predictions for records from the replayed dataset."""
    st.title("Detection Records")
    st.caption(
        "Browse model predictions generated for the testing dataset."
    )

    detections = data["detections"]

    if detections is None:
        display_missing_message(
            "The detection results file is missing."
        )
        return

    valid, message = validate_detections(detections)

    if not valid:
        st.error(message)
        return

    try:
        detections = ensure_detection_values(detections)
    except ValueError as error:
        st.error(str(error))
        return

    filtered = detections.copy()

    if "predicted_class" in filtered.columns:
        classes = sorted(
            filtered["predicted_class"]
            .dropna()
            .astype(str)
            .unique()
            .tolist()
        )

        selected_class = st.selectbox(
            "Filter prediction class",
            options=["All classes"] + classes,
        )

        if selected_class != "All classes":
            filtered = filtered.loc[
                filtered["predicted_class"].astype(str) == selected_class
            ]

    if "severity" in filtered.columns:
        severities = sorted(
            filtered["severity"]
            .dropna()
            .astype(str)
            .unique()
            .tolist()
        )

        chosen_severities = st.multiselect(
            "Filter severity",
            options=severities,
            default=severities,
        )

        filtered = filtered.loc[
            filtered["severity"].astype(str).isin(chosen_severities)
        ]

    maximum_rows = min(1000, len(filtered))

    if maximum_rows == 0:
        st.info("No records match the selected filters.")
        return

    row_limit = st.slider(
        "Number of records to display",
        min_value=10,
        max_value=max(10, maximum_rows),
        value=min(100, maximum_rows),
        step=10 if maximum_rows >= 10 else 1,
    )

    st.write(f"Matching records: **{len(filtered):,}**")

    st.dataframe(
        filtered.head(row_limit),
        use_container_width=True,
        hide_index=True,
    )

    st.download_button(
        "Download filtered detection records",
        data=filtered.to_csv(index=False).encode("utf-8"),
        file_name="filtered_detection_records.csv",
        mime="text/csv",
    )


