def show_file_status(data: dict) -> None:
    """Show which generated reports are currently available."""
    statuses = [
        (
            "Model comparison",
            data["model_comparison"] is not None,
        ),
        (
            "Detection results",
            data["detections"] is not None,
        ),
        (
            "Threat alerts",
            data["alerts"] is not None,
        ),
        (
            "Detection summary",
            data["summary"] is not None,
        ),
        (
            "Evaluation results",
            data["evaluation"] is not None,
        ),
    ]

    with st.sidebar.expander("Generated report status", expanded=False):
        for name, available in statuses:
            symbol = "Available" if available else "Missing"
            st.write(f"**{name}:** {symbol}")


def validate_model_comparison(dataframe: pd.DataFrame):
    """Validate the columns used by the model-performance charts."""
    required = {"model", *METRIC_COLUMNS}

    missing = required - set(dataframe.columns)

    if missing:
        return False, (
            "The model comparison report is missing these columns: "
            f"{sorted(missing)}"
        )

    return True, None


def validate_detections(dataframe: pd.DataFrame):
    """Validate the fields required for the main dashboard metrics."""
    required = {
        "attack_score",
        "predicted_label",
        "predicted_class",
        "severity",
    }

    missing = required - set(dataframe.columns)

    if missing:
        return False, (
            "The detection report is missing these columns: "
            f"{sorted(missing)}"
        )

    return True, None


def ensure_numeric_metrics(dataframe: pd.DataFrame):
    """Convert model evaluation metrics to numeric values safely."""
    cleaned = dataframe.copy()

    for column in METRIC_COLUMNS:
        cleaned[column] = pd.to_numeric(
            cleaned[column],
            errors="coerce",
        )

        if cleaned[column].isna().any():
            raise ValueError(
                f"Evaluation metric '{column}' contains invalid values."
            )

        if not cleaned[column].between(0, 1).all():
            raise ValueError(
                f"Evaluation metric '{column}' must be between 0 and 1."
            )

    return cleaned


def ensure_detection_values(dataframe: pd.DataFrame):
    """Validate detection scores and binary predictions."""
    cleaned = dataframe.copy()

    cleaned["attack_score"] = pd.to_numeric(
        cleaned["attack_score"],
        errors="coerce",
    )

    cleaned["predicted_label"] = pd.to_numeric(
        cleaned["predicted_label"],
        errors="coerce",
    )

    if (
        cleaned["attack_score"].isna().any()
        or cleaned["predicted_label"].isna().any()
    ):
        raise ValueError(
            "Detection results contain invalid numeric values."
        )

    if not cleaned["attack_score"].between(0, 1).all():
        raise ValueError(
            "Detection scores must be between 0 and 1."
        )

    if not cleaned["predicted_label"].isin([0, 1]).all():
        raise ValueError(
            "Predicted labels must be either 0 or 1."
        )

    cleaned["predicted_label"] = (
        cleaned["predicted_label"].astype(int)
    )

    return cleaned


def display_missing_message(message: str) -> None:
    """Display actionable guidance for unavailable pipeline outputs."""
    st.warning(message)

    st.markdown(
        """
        To populate the dashboard, complete the earlier pipeline stages
        and generate their output files.

        **Recommended execution order:**

        1. `python -m src.model_training`
        2. `python -m src.model_evaluation`
        3. `python -m src.threat_detection`
        4. `python -m src.visualization`

        Run these commands from the project root after the datasets and
        dependencies are ready. Do not create fabricated reports to
        make the dashboard appear populated.
        """
    )


def show_image(path: Path, caption: str) -> None:
    """Display a locally generated image if it exists."""
    if path.is_file():
        st.image(
            str(path),
            caption=caption,
            use_container_width=True,
        )
    else:
        st.info(
            f"Visualization not available yet: "
            f"{path.relative_to(PROJECT_ROOT)}"
        )


