@st.cache_data(ttl=60, show_spinner=False)
def read_csv_cached(path_string: str, modified_time: int):
    """
    Load a CSV file and cache it until the file changes or the cache expires.

    The modification timestamp is included to prevent the dashboard from
    indefinitely displaying outdated pipeline results.
    """
    path = Path(path_string)

    if not path.is_file():
        return None, "File does not exist."

    try:
        dataframe = pd.read_csv(path)

        if dataframe.empty:
            return None, "File contains no data rows."

        return dataframe, None

    except (OSError, ValueError, pd.errors.ParserError) as error:
        return None, str(error)


@st.cache_data(ttl=60, show_spinner=False)
def read_json_cached(path_string: str, modified_time: int):
    """Read and cache a JSON results file."""
    path = Path(path_string)

    if not path.is_file():
        return None, "File does not exist."

    try:
        with path.open("r", encoding="utf-8") as file:
            return json.load(file), None

    except (OSError, ValueError, json.JSONDecodeError) as error:
        return None, str(error)


def load_csv_file(path: Path):
    """Load a CSV file, returning a DataFrame or a readable error."""
    if not path.is_file():
        return None, f"Missing file: {path.relative_to(PROJECT_ROOT)}"

    try:
        modified_time = path.stat().st_mtime_ns
    except OSError as error:
        return None, str(error)

    return read_csv_cached(str(path), modified_time)


def load_json_file(path: Path):
    """Load a JSON file, returning its contents or a readable error."""
    if not path.is_file():
        return None, f"Missing file: {path.relative_to(PROJECT_ROOT)}"

    try:
        modified_time = path.stat().st_mtime_ns
    except OSError as error:
        return None, str(error)

    return read_json_cached(str(path), modified_time)


def load_dashboard_data():
    """Load all available reports generated by the pipeline."""
    model_comparison, model_error = load_csv_file(
        MODEL_COMPARISON_PATH
    )

    detections, detection_error = load_csv_file(
        DETECTION_RESULTS_PATH
    )

    alerts, alerts_error = load_csv_file(
        THREAT_ALERTS_PATH
    )

    summary, summary_error = load_json_file(SUMMARY_PATH)

    evaluation, evaluation_error = load_json_file(
        EVALUATION_RESULTS_PATH
    )

    return {
        "model_comparison": model_comparison,
        "model_error": model_error,
        "detections": detections,
        "detection_error": detection_error,
        "alerts": alerts,
        "alerts_error": alerts_error,
        "summary": summary,
        "summary_error": summary_error,
        "evaluation": evaluation,
        "evaluation_error": evaluation_error,
    }


