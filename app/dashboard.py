def render_overview(data: dict) -> None:
    """Render the main dashboard overview."""
    st.title("AI-Powered Cybersecurity Threat Detection")
    st.caption(
        "Offline network intrusion detection and machine-learning "
        "security analytics."
    )

    summary = data["summary"]
    detections = data["detections"]
    comparison = data["model_comparison"]

    records_processed = 0
    alert_count = 0
    high_alert_count = 0
    normal_count = 0

    if detections is not None:
        valid, message = validate_detections(detections)

        if valid:
            try:
                detections = ensure_detection_values(detections)

                records_processed = len(detections)

                alert_rows = detections.loc[
                    detections["predicted_label"] == 1
                ]

                alert_count = len(alert_rows)

                normal_count = records_processed - alert_count

                high_alert_count = int(
                    (
                        alert_rows["severity"].astype(str).str.upper()
                        == "HIGH"
                    ).sum()
                )

            except ValueError as error:
                st.error(str(error))
        else:
            st.error(message)

    # Summary information comes from the actual generated detection report.
    if isinstance(summary, dict):
        records_processed = int(
            summary.get("records_processed", records_processed)
        )
        alert_count = int(
            summary.get("alerts_generated", alert_count)
        )

    st.subheader("Detection overview")

    metric_columns = st.columns(4)

    metric_columns[0].metric(
        "Records processed",
        f"{records_processed:,}",
    )

    metric_columns[1].metric(
        "Predicted attacks",
        f"{alert_count:,}",
    )

    metric_columns[2].metric(
        "High-severity alerts",
        f"{high_alert_count:,}",
    )

    metric_columns[3].metric(
        "Predicted normal",
        f"{normal_count:,}",
    )

    if comparison is not None:
        valid, message = validate_model_comparison(comparison)

        if valid:
            try:
                comparison = ensure_numeric_metrics(comparison)

                st.subheader("Model performance")

                display_columns = [
                    "model",
                    "accuracy",
                    "precision_attack",
                    "recall_attack",
                    "f1_score_attack",
                ]

                st.dataframe(
                    comparison[display_columns].style.format(
                        {
                            "accuracy": "{:.4f}",
                            "precision_attack": "{:.4f}",
                            "recall_attack": "{:.4f}",
                            "f1_score_attack": "{:.4f}",
                        }
                    ),
                    use_container_width=True,
                    hide_index=True,
                )

                st.bar_chart(
                    comparison.set_index("model")[
                        [
                            "accuracy",
                            "precision_attack",
                            "recall_attack",
                            "f1_score_attack",
                        ]
                    ],
                    y_label="Score",
                )

            except ValueError as error:
                st.error(str(error))
        else:
            st.error(message)

    st.subheader("Alert severity")

    if detections is not None and "severity" in detections.columns:
        severities = (
            detections.loc[
                detections["predicted_label"] == 1,
                "severity",
            ]
            .astype(str)
            .str.upper()
            .value_counts()
            .reindex(["HIGH", "MEDIUM", "LOW"], fill_value=0)
        )

        if severities.sum() > 0:
            st.bar_chart(
                severities,
                y_label="Number of alerts",
            )
        else:
            st.info(
                "No attack predictions are available in the current report."
            )
    else:
        st.info(
            "Generate the threat detection report to display alert severity."
        )

    st.subheader("Recent high-priority alerts")

    alerts = data["alerts"]

    if alerts is not None and not alerts.empty:
        if "severity" in alerts.columns:
            high_alerts = alerts.loc[
                alerts["severity"].astype(str).str.upper() == "HIGH"
            ]
        else:
            high_alerts = alerts.iloc[0:0]

        if high_alerts.empty:
            st.info("No high-severity alert records are present.")
        else:
            st.dataframe(
                high_alerts.head(10),
                use_container_width=True,
                hide_index=True,
            )
    else:
        st.info(
            "The threat alert report is missing or contains no alerts."
        )

    st.divider()

    st.caption(
        "This dashboard presents model predictions from an offline "
        "dataset simulation. A model-generated alert is not confirmation "
        "of a real-world security incident."
    )


