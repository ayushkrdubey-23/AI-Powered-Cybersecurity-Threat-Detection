# Main Streamlit application
# ---------------------------------------------------------------------

def main() -> None:
    """Render the interactive dashboard."""
    st.set_page_config(
        page_title="AI Cybersecurity Threat Detection",
        page_icon="🛡️",
        layout="wide",
        initial_sidebar_state="expanded",
    )

    st.sidebar.title("Cybersecurity SOC")
    st.sidebar.caption("AI-Powered Threat Detection System")

    page = st.sidebar.radio(
        "Navigation",
        options=[
            "Overview",
            "Model Evaluation",
            "Threat Alerts",
            "Detection Records",
            "Graphs and Reports",
        ],
    )

    st.sidebar.divider()

    st.sidebar.write("**Project mode**")
    st.sidebar.info(
        "Offline dataset simulation. This dashboard does not monitor "
        "live networks."
    )

    data = load_dashboard_data()

    show_file_status(data)

    if page == "Overview":
        render_overview(data)

    elif page == "Model Evaluation":
        render_model_evaluation(data)

    elif page == "Threat Alerts":
        render_threat_alerts(data)

    elif page == "Detection Records":
        render_detection_records(data)

    elif page == "Graphs and Reports":
        render_graphs_and_reports()


if __name__ == "__main__":
    main()
