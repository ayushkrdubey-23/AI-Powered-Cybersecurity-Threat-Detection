def render_model_evaluation(data: dict) -> None:
    """Display evaluation metrics, confusion matrices, and reports."""
    st.title("Model Evaluation")
    st.caption("Results from the held-out UNSW-NB15 testing dataset.")

    comparison = data["model_comparison"]

    if comparison is None:
        display_missing_message(
            "The model comparison file is missing."
        )
        return

    valid, message = validate_model_comparison(comparison)

    if not valid:
        st.error(message)
        return

    try:
        comparison = ensure_numeric_metrics(comparison)
    except ValueError as error:
        st.error(str(error))
        return

    st.subheader("Classification metrics")

    st.dataframe(
        comparison.style.format(
            {
                column: "{:.4f}"
                for column in METRIC_COLUMNS
            }
        ),
        use_container_width=True,
        hide_index=True,
    )

    selected_metric = st.selectbox(
        "Choose a metric to compare",
        options=[
            "accuracy",
            "precision_attack",
            "recall_attack",
            "f1_score_attack",
            "false_positive_rate",
        ],
        format_func=lambda value: {
            "accuracy": "Accuracy",
            "precision_attack": "Precision (attack)",
            "recall_attack": "Recall (attack)",
            "f1_score_attack": "F1 score (attack)",
            "false_positive_rate": "False-positive rate",
        }[value],
    )

    chart_data = comparison.set_index("model")[[selected_metric]]

    st.bar_chart(
        chart_data,
        y_label="Score",
    )

    st.subheader("Confusion matrices")

    left, right = st.columns(2)

    with left:
        show_image(
            CONFUSION_MATRIX_FILES["Logistic Regression"],
            "Logistic Regression confusion matrix",
        )

    with right:
        show_image(
            CONFUSION_MATRIX_FILES["Random Forest"],
            "Random Forest confusion matrix",
        )

    st.subheader("Classification report")

    if CLASSIFICATION_REPORT_PATH.is_file():
        try:
            report_text = CLASSIFICATION_REPORT_PATH.read_text(
                encoding="utf-8"
            )

            st.text(report_text)

            st.download_button(
                "Download classification report",
                data=report_text,
                file_name="classification_report.txt",
                mime="text/plain",
            )

        except OSError as error:
            st.error(f"Could not read classification report: {error}")
    else:
        st.info(
            "The text report is missing. Run the evaluation module first."
        )

    st.caption(
        "High recall can help reduce missed attacks, while precision "
        "and false-positive rate help assess the operational burden "
        "of unnecessary alerts."
    )


