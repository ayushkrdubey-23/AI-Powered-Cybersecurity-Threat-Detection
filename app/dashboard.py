def render_threat_alerts(data: dict) -> None:
    """Provide searchable and filterable access to generated threat alerts."""
    st.title("Threat Alerts")
    st.caption(
        "Investigate model-generated alerts from the offline simulation."
    )

    alerts = data["alerts"]

    if alerts is None:
        detections = data["detections"]

        if detections is None:
            display_missing_message(
                "Neither the threat alert report nor detection records "
                "are available."
            )
            return

        if "predicted_label" not in detections.columns:
            st.error(
                "The detection report does not contain predicted_label."
            )
            return

        alerts = detections.loc[
            pd.to_numeric(
                detections["predicted_label"],
                errors="coerce",
            ) == 1
        ].copy()

    if alerts.empty:
        st.info(
            "The current simulation contains no generated threat alerts."
        )
        return

    if "severity" not in alerts.columns:
        st.error("The alert report is missing the severity field.")
        return

    filtered = alerts.copy()

    severity_options = sorted(
        filtered["severity"].dropna().astype(str).unique().tolist()
    )

    selected_severities = st.multiselect(
        "Filter by severity",
        options=severity_options,
        default=severity_options,
    )

    filtered = filtered.loc[
        filtered["severity"].astype(str).isin(selected_severities)
    ]

    if "attack_score" in filtered.columns:
        filtered["attack_score"] = pd.to_numeric(
            filtered["attack_score"],
            errors="coerce",
        )

        filtered = filtered.dropna(
            subset=["attack_score"]
        )

        if filtered.empty:
            st.info("No alerts match the selected filters.")
            return

        minimum_score = float(
            filtered["attack_score"].min()
        )

        maximum_score = float(
            filtered["attack_score"].max()
        )

        if minimum_score < maximum_score:
            lower, upper = st.slider(
                "Filter by attack score",
                min_value=0.0,
                max_value=1.0,
                value=(
                    max(0.0, minimum_score),
                    min(1.0, maximum_score),
                ),
                step=0.01,
            )

            filtered = filtered.loc[
                filtered["attack_score"].between(lower, upper)
            ]

    if "protocol" in filtered.columns:
        protocol_values = sorted(
            filtered["protocol"]
            .dropna()
            .astype(str)
            .unique()
            .tolist()
        )

        selected_protocols = st.multiselect(
            "Filter by protocol",
            options=protocol_values,
            default=protocol_values,
        )

        filtered = filtered.loc[
            filtered["protocol"].astype(str).isin(selected_protocols)
            | filtered["protocol"].isna()
        ]

    st.subheader("Filtered alerts")
    st.write(f"Matching alerts: **{len(filtered):,}**")

    st.dataframe(
        filtered,
        use_container_width=True,
        hide_index=True,
    )

    csv_content = filtered.to_csv(
        index=False
    ).encode("utf-8")

    st.download_button(
        "Download filtered alerts",
        data=csv_content,
        file_name="filtered_threat_alerts.csv",
        mime="text/csv",
    )

    st.caption(
        "Severity follows the thresholds configured in the detection "
        "module. Confirm suspicious activity with additional evidence "
        "before treating an alert as an actual incident."
    )


