def render_graphs_and_reports() -> None:
    """Display the PNG plots generated by the visualization module."""
    st.title("Graphs and Reports")
    st.caption(
        "Visual evidence generated by the evaluation and detection pipeline."
    )

    st.subheader("Model performance and security analytics")

    for caption, path in CHART_FILES.items():
        show_image(path, caption)

    st.subheader("Confusion matrices")

    for caption, path in CONFUSION_MATRIX_FILES.items():
        show_image(path, f"{caption} confusion matrix")

    st.subheader("Evaluation results")

    if EVALUATION_RESULTS_PATH.is_file():
        evaluation, error = load_json_file(
            EVALUATION_RESULTS_PATH
        )

        if error is None:
            with st.expander("View evaluation JSON", expanded=False):
                st.json(evaluation)

            st.download_button(
                "Download evaluation results",
                data=json.dumps(
                    evaluation,
                    indent=4,
                ),
                file_name="evaluation_results.json",
                mime="application/json",
            )
        else:
            st.error(error)
    else:
        st.info(
            "Evaluation JSON is missing. Run the model evaluation module."
        )

    st.subheader("Detection summary")

    if SUMMARY_PATH.is_file():
        summary, error = load_json_file(SUMMARY_PATH)

        if error is None:
            st.json(summary)

            st.download_button(
                "Download detection summary",
                data=json.dumps(
                    summary,
                    indent=4,
                ),
                file_name="detection_summary.json",
                mime="application/json",
            )
        else:
            st.error(error)
    else:
        st.info(
            "Detection summary is missing. Run the threat detection module."
        )


